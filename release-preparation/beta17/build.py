from pathlib import Path
import zipfile,json,hashlib,datetime,re,shutil
b=Path(__file__).parent;s=b/'source';r=s/'runtime'
# Same steps as build.ps1. Skills: the approved library at the repository root is the only source;
# its catalog is regenerated and it is copied into the installer payload.
CATEGORIES={'revit':'Revit','autocad':'AutoCAD','3ds-max':'3ds Max','other-software':'Other software','linkedin-marketing':'LinkedIn and marketing',
 'branding-ci':'Personal branding and corporate identity','general':'General and office','uncategorized':'Not yet categorised'}
def skill_folders(root):
 found=[]
 for d in sorted(p for p in root.iterdir() if p.is_dir() and not p.name.startswith('.')):
  if (d/'SKILL.md').is_file():found.append((d.name,'',d))
  elif d.name in CATEGORIES:found+=[(k.name,d.name,k) for k in sorted(d.iterdir()) if k.is_dir() and (k/'SKILL.md').is_file()]
 names=[n for n,_,_ in found]
 dup=sorted({n for n in names if names.count(n)>1})
 if dup:raise SystemExit('Skill names must be unique across categories: '+', '.join(dup))
 return found
def describe(path):
 m=re.search(r'^description:\s*(.+)$',(path/'SKILL.md').read_text(encoding='utf-8-sig'),re.M)
 return m.group(1).strip().strip('"') if m else ''
def catalog(root,prefix=''):
 skills=skill_folders(root);lines=[]
 for slug,title in CATEGORIES.items():
  members=[x for x in skills if x[1]==slug]
  if not members and slug=='uncategorized':continue
  lines+=['',f'### {title}','']+([f'- [{n}]({prefix}{slug}/{n}/SKILL.md): {describe(p)}' for n,_,p in members] or ['_No approved skills yet._'])
 return '\n'.join(lines)
library=(b/'../../.agents/skills').resolve();shipped=r/'.agents/skills'
if library.is_dir():
 (library/'README.md').write_text('# Skill library\n\nApproved skills, grouped by category. Each skill lives in `<category>/<skill-name>/SKILL.md` and declares `category: <category>` in its frontmatter. Skill names must be unique across categories, because Codex and Claude install them side by side.\n\nThis file is generated by `release-preparation/beta17/build.ps1`; do not edit it by hand.\n'+catalog(library)+'\n',encoding='utf-8')
 shutil.rmtree(shipped,ignore_errors=True);shutil.copytree(library,shipped)
entry=('---\nname: autodesk-mcp-bim-workflows\ndescription: Work with Revit, AutoCAD and other software through Smart Autodesk Connector, using the team\'s approved workflow skills grouped by category.\n---\n\n'
 '# Smart Autodesk Connector workflows\n\nUse this skill for work performed through the local Smart Autodesk Connector, and for the team\'s other approved workflows.\n\n'
 'Read only the reference that matches the current task. Preserve the user\'s model and documentation intent, follow every MUST rule in the selected reference, and verify live model changes by reading the affected elements back through the connector. A skill supplies procedure; it does not grant permission for unrelated changes.\n\n'
 '## Workflow references\n'+catalog(shipped,'references/')+'\n')
with zipfile.ZipFile(s/'Autodesk MCP Skills for Claude.zip','w',zipfile.ZIP_DEFLATED) as z:
 z.writestr('autodesk-mcp-bim-workflows/SKILL.md',entry)
 for p in sorted(shipped.rglob('*')):
  if p.is_file() and p.relative_to(shipped).as_posix()!='README.md':z.write(p,'autodesk-mcp-bim-workflows/references/'+p.relative_to(shipped).as_posix())
with zipfile.ZipFile(s/'Support/Autodesk-MCP-Payload.zip','w',zipfile.ZIP_DEFLATED) as z:
 for p in sorted(r.rglob('*')):
  if p.is_file():z.write(p,'Autodesk-MCP-Payload/'+p.relative_to(r).as_posix())
version=(r/'VERSION').read_text().strip()
name=f'Autodesk-MCP-Connector-{version}.zip'
with zipfile.ZipFile(b/name,'w',zipfile.ZIP_DEFLATED) as z:
 for p in sorted(s.rglob('*')):
  if p.is_file() and r not in p.parents:z.write(p,f'Autodesk-MCP-Connector-{version}/'+p.relative_to(s).as_posix())
h=hashlib.sha256((b/name).read_bytes()).hexdigest().upper()
(b/'latest.json').write_text(json.dumps(dict(schema_version=1,version=version,download_url=f'https://github.com/EhabHassan007/Autodesk-MCP-Releases/releases/download/v{version}/'+name,sha256=h,published_at=datetime.datetime.now(datetime.timezone.utc).isoformat()),indent=2)+'\n')
notes=(b/'RELEASE-NOTES.md').read_text().split('\nSHA-256:')[0]+'\nSHA-256: '+h+'\n';(b/'RELEASE-NOTES.md').write_text(notes)
with zipfile.ZipFile(b/'beta17-github-upload.zip','w',zipfile.ZIP_DEFLATED) as z:
 for n in [name,'latest.json','RELEASE-NOTES.md']:z.write(b/n,n)
with zipfile.ZipFile(b/'beta17-source-and-tests.zip','w',zipfile.ZIP_DEFLATED) as z:
 for folder in [r,b/'tests']:
  for p in sorted(folder.rglob('*')):
   if p.is_file():z.write(p,p.relative_to(b).as_posix())
 z.write(b/'build.py','build.py')
 z.write(b/'build.ps1','build.ps1')
print(name,h)
